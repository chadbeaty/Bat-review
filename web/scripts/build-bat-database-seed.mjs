#!/usr/bin/env node
// Builds supabase/seed/bat-database.sql from the research files in ../data:
//   families.json → product_lines, and each product's product_line_id (from bats.json "family")
//   lineage.json  → product_lineage rows (predecessor in the catalog, siblings) and products.lineage_note
//   reviews.json  → published_reviews and their links to models and lines
// plus manufacturer warranty terms from docs/NEW-BAT-RESEARCH.md. Every lineage row is unverified.
// Release dates: the research notes give no documented date for any model, so none are written.
// Run after the catalog seed (it updates products the catalog seed creates). Safe to run more than once.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { BUILD, MATERIAL, weightingType } from "./catalog-mapping.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const out = join(here, "..", "supabase", "seed", "bat-database.sql");

const read = async (f) => JSON.parse(await readFile(join(root, "data", f), "utf8"));
const { bats } = await read("bats.json");
const { families } = await read("families.json");
const { entries, generated } = await read("lineage.json");
const { reviews, updated: reviewsUpdated } = await read("reviews.json");

const sql = (v) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(sql).join(",")}]::text[]`;
const json = (o) => `${sql(JSON.stringify(o))}::jsonb`;
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const batById = new Map(bats.map((b) => [b.id, b]));
const familyIds = new Set(families.map((f) => f.id));

// Fail loudly on broken references instead of writing a seed that silently drops links.
const problems = [];
for (const b of bats) if (b.family && !familyIds.has(b.family)) problems.push(`bat ${b.id}: unknown family ${b.family}`);
for (const e of entries) {
  if (!batById.has(e.bat_id)) problems.push(`lineage: unknown bat ${e.bat_id}`);
  if (e.predecessor.bat_id && !batById.has(e.predecessor.bat_id)) problems.push(`lineage: unknown predecessor ${e.predecessor.bat_id}`);
  for (const s of e.siblings) if (!batById.has(s)) problems.push(`lineage: unknown sibling ${s}`);
}
for (const r of reviews) {
  for (const b of r.bats) if (!batById.has(b)) problems.push(`review ${r.id}: unknown bat ${b}`);
  for (const f of r.families) if (!familyIds.has(f)) problems.push(`review ${r.id}: unknown family ${f}`);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

/** Same build, load, barrel, material and stamps: a variant (for example a signature edition) rather than a different platform. */
function sameSpecs(a, b) {
  return (
    BUILD[a.build] === BUILD[b.build] &&
    weightingType(a) === weightingType(b) &&
    (a.barrel ?? null) === (b.barrel ?? null) &&
    MATERIAL[a.material] === MATERIAL[b.material] &&
    [...a.stamps].sort().join("/") === [...b.stamps].sort().join("/")
  );
}

const firstUrl = (sources) => sources.find((s) => /^https?:\/\//.test(s)) ?? null;
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + "…" : s);

const lines = [
  `-- Generated by scripts/build-bat-database-seed.mjs from data/families.json, data/lineage.json (${generated}) and data/reviews.json (${reviewsUpdated ?? "undated"}). Do not edit by hand.`,
  "-- Lineage is research, not manufacturer fact: every row is unverified and carries its confidence and basis.",
  "",
  "-- Product lines",
];

for (const f of families) {
  lines.push(
    `insert into public.product_lines (id, manufacturer_id, name, aliases, notes)
select ${sql(f.id)}, (select id from public.manufacturers where slug = ${sql(slugify(f.brand))}), ${sql(f.name)}, ${arr(f.aliases ?? [])}, ${arr(f.notes ?? [])}
on conflict (id) do update set manufacturer_id = excluded.manufacturer_id, name = excluded.name, aliases = excluded.aliases, notes = excluded.notes;`
  );
}

lines.push("", "-- Each product's line");
for (const b of bats) {
  if (b.family) lines.push(`update public.products set product_line_id = ${sql(b.family)} where slug = ${sql(b.id)};`);
}

lines.push("", "-- Lineage notes (including predecessors that are not in the catalog)");
for (const e of entries) {
  const note = {
    predecessor_name: e.predecessor.name ?? null,
    predecessor_in_catalog: Boolean(e.predecessor.bat_id),
    changes: e.changes.filter((c) => c && c !== "unknown"),
    confidence: e.confidence,
    basis: e.basis,
    sources: e.sources,
    researched_on: generated,
  };
  lines.push(`update public.products set lineage_note = ${json(note)} where slug = ${sql(e.bat_id)};`);
}

lines.push("", "-- Lineage links between catalog models (read: related_product_id is the <relation> of product_id)");
const linkRow = (from, to, relation, confidence, basis, sourceUrl) =>
  `insert into public.product_lineage (product_id, related_product_id, relation, confidence, basis, source_url, verified)
select a.id, b.id, ${sql(relation)}, ${sql(confidence)}, ${sql(clip(basis, 1000))}, ${sql(sourceUrl)}, false
from public.products a, public.products b where a.slug = ${sql(from)} and b.slug = ${sql(to)}
on conflict do nothing;`;

let links = 0;
for (const e of entries) {
  if (e.predecessor.bat_id) {
    lines.push(linkRow(e.bat_id, e.predecessor.bat_id, "predecessor", e.confidence, e.basis, firstUrl(e.sources)));
    links++;
  }
  for (const s of e.siblings) {
    const relation = sameSpecs(batById.get(e.bat_id), batById.get(s)) ? "variant" : "same_platform";
    const basis = relation === "variant" ? `Same line, year and specs in our catalog data. ${e.basis}` : `Same line and year. ${e.basis}`;
    lines.push(linkRow(e.bat_id, s, relation, e.confidence, basis, firstUrl(e.sources)));
    links++;
  }
}

lines.push("", "-- Published external reviews");
for (const r of reviews) {
  lines.push(
    `insert into public.published_reviews (source_key, kind, title, url, source, rating_text, published_on, summary)
values (${sql(r.id)}, ${sql(r.kind)}, ${sql(r.title)}, ${sql(r.url)}, ${sql(r.source)}, ${sql(r.rating)}, ${r.date ? `${sql(r.date)}::date` : "null"}, ${sql(r.summary)})
on conflict (source_key) do update set kind = excluded.kind, title = excluded.title, url = excluded.url, source = excluded.source,
  rating_text = excluded.rating_text, published_on = excluded.published_on, summary = excluded.summary;`
  );
  for (const b of r.bats) {
    lines.push(
      `insert into public.published_review_products (review_id, product_id)
select r.id, p.id from public.published_reviews r, public.products p where r.source_key = ${sql(r.id)} and p.slug = ${sql(b)}
on conflict do nothing;`
    );
  }
  for (const f of r.families) {
    lines.push(
      `insert into public.published_review_lines (review_id, product_line_id)
select r.id, ${sql(f)} from public.published_reviews r where r.source_key = ${sql(r.id)}
on conflict do nothing;`
    );
  }
}

// Warranty terms from docs/NEW-BAT-RESEARCH.md (1 November 2026). Other brands stay null: "not on file".
const WARRANTY_SOURCE = "Research summary, 1 November 2026 (docs/NEW-BAT-RESEARCH.md). Check the manufacturer's current terms.";
const RAWLINGS = "One year from purchase, one-time repair or replacement. The original receipt is required.";
const warranties = [
  ["easton", RAWLINGS],
  ["miken", RAWLINGS],
  ["worth", RAWLINGS],
  ["demarini", "One year from purchase. Senior bats are excluded from the warranty."],
  ["monsta", "Sold without a manufacturer warranty. A separate replacement plan is available to buy."],
];
lines.push("", "-- Manufacturer warranty terms");
for (const [slug, summary] of warranties) {
  lines.push(
    `update public.manufacturers set warranty_summary = ${sql(summary)}, warranty_source = ${sql(WARRANTY_SOURCE)} where slug = ${sql(slug)};`
  );
}

await mkdir(dirname(out), { recursive: true });
await writeFile(out, lines.join("\n") + "\n");
console.log(`Wrote ${families.length} lines, ${entries.length} lineage notes, ${links} lineage links and ${reviews.length} reviews to ${out}`);
