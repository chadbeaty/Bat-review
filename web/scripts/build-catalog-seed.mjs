#!/usr/bin/env node
// Builds supabase/seed/catalog.sql from the researched bat catalog in ../data/bats.json.
// Every product is marked unverified: specs came from retailer and manufacturer listings, not from our own checks.
// Fields the listing did not state are left unknown rather than guessed (for example weights, barrel diameter).

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { weightingType, endloadOz, MATERIAL, BUILD } from "./catalog-mapping.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const out = join(here, "..", "supabase", "seed", "catalog.sql");

const { bats, updated } = JSON.parse(await readFile(join(root, "data", "bats.json"), "utf8"));
const { families } = JSON.parse(await readFile(join(root, "data", "families.json"), "utf8"));
const familyName = new Map(families.map((f) => [f.id, f.name.replace(/\s*\(.*?\)\s*/g, "").trim()]));

const sql = (v) => (v == null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(sql).join(",")}]::text[]`;
const json = (o) => `${sql(JSON.stringify(o))}::jsonb`;
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const lines = [
  `-- Generated by scripts/build-catalog-seed.mjs from data/bats.json (catalog dated ${updated}). Do not edit by hand.`,
  "-- All rows are unverified retailer/manufacturer listing data. See products.data_source and verification_source.",
  "",
];

for (const b of bats) {
  const name = `${b.year} ${b.brand} ${b.model}`;
  const stamps = b.stamps;
  const specs = {
    stamps,
    construction: b.build,
    material: b.material,
    weighting: b.load,
    load_name: b.loadName ?? null,
    barrel_length_inches: b.barrel ?? null,
    listed_weights_oz: b.weights ?? null,
    manufacturer_part_number: b.sku ?? null,
    listed_price_usd: b.price ?? null,
    listed_price_is_typical: Boolean(b.priceApprox),
  };
  lines.push(
    `insert into public.products (category_id, manufacturer_id, product_name, model_name, model_year, slug, official_product_url, product_specifications, aliases, original_retail_price_cents, original_price_source, original_price_verified, certification_association, certification_status, certification_source, catalog_status, data_source)
select c.id, m.id, ${sql(name)}, ${sql(b.model)}, ${b.year}, ${sql(b.id)}, null, ${json(specs)}, ${arr([familyName.get(b.family) || ""].filter(Boolean))},
  ${b.price != null && !b.priceApprox ? Math.round(b.price * 100) : "null"}, ${sql(b.source || null)}, false, ${arr(stamps)}, 'unverified', ${sql(b.source || null)}, 'published', 'researched listing data, ${updated}'
from public.product_categories c, public.manufacturers m
where c.slug = 'bats' and m.slug = ${sql(slugify(b.brand))}
on conflict (slug) do update set
  product_name = excluded.product_name, model_name = excluded.model_name, model_year = excluded.model_year,
  product_specifications = excluded.product_specifications, aliases = excluded.aliases,
  original_retail_price_cents = excluded.original_retail_price_cents, original_price_source = excluded.original_price_source,
  certification_association = excluded.certification_association, certification_source = excluded.certification_source;`
  );

  const weights = b.weights && b.weights.length ? b.weights : [null];
  for (const w of weights) {
    lines.push(
      `insert into public.bat_specifications (product_id, weight_oz, barrel_length_inches, weighting_type, endload_oz, construction_type, construction_material, certification, model_year, product_line, manufacturer_part_number, verified, verification_source)
select p.id, ${w ?? "null"}, ${b.barrel ?? "null"}, ${sql(weightingType(b))}, ${endloadOz(b) ?? "null"}, ${sql(BUILD[b.build] || "unknown")}, ${sql(MATERIAL[b.material] || "unknown")}, ${sql(stamps.join(" / "))}, ${b.year}, ${sql(familyName.get(b.family) || null)}, ${sql(b.sku || null)}, false, ${sql(b.source || null)}
from public.products p where p.slug = ${sql(b.id)}
on conflict (product_id, (coalesce(weight_oz, 0))) do nothing;`
    );
  }
}

await mkdir(dirname(out), { recursive: true });
await writeFile(out, lines.join("\n") + "\n");
console.log(`Wrote ${bats.length} bats to ${out}`);

// Compact copy for the site to show before the database is connected (and in tests).
const fallbackOut = join(here, "..", "src", "data", "catalog-fallback.json");
const fallback = bats.map((b) => ({
  slug: b.id,
  name: `${b.brand} ${b.model}`,
  manufacturer: b.brand,
  manufacturerSlug: slugify(b.brand),
  modelYear: b.year,
  productLine: familyName.get(b.family) || null,
  certifications: b.stamps,
  weightingType: weightingType(b),
  constructionType: BUILD[b.build] || "unknown",
  material: MATERIAL[b.material] || "unknown",
  barrelLengthInches: b.barrel ?? null,
}));
await mkdir(dirname(fallbackOut), { recursive: true });
await writeFile(fallbackOut, JSON.stringify({ generatedFrom: `data/bats.json (${updated})`, bats: fallback }, null, 1) + "\n");
console.log(`Wrote ${fallback.length} bats to ${fallbackOut}`);
