#!/usr/bin/env python3
"""
Bakes the Chivo letters the logo files need (taglines on the bag tag, the patch and the tagline lockup) into
src/brand/type.ts as plain SVG path data, so every logo file is pure vector shapes with no font dependency.

    pip install fonttools && python3 scripts/bake-brand-type.py

Coordinates: cap height = 100 units, the top of the capitals at y = 0, the baseline at y = 100 (y down, like SVG).
Only M, L, Q and Z commands are written, all absolute, so src/brand/emblem.ts can move, scale and rotate them.
"""
import os
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.basePen import decomposeQuadraticSegment

ROOT = os.path.join(os.path.dirname(__file__), "..")
FONT = os.path.join(ROOT, "src/brand/fonts/Chivo-900Italic.ttf")
OUT = os.path.join(ROOT, "src/brand/type.ts")
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.-'"

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
cap = font["OS/2"].sCapHeight
k = 100.0 / cap


def fmt(n):
    v = round(n, 2)
    return str(int(v)) if v == int(v) else str(v)


def pt(p):
    x, y = p
    return f"{fmt(x * k)} {fmt(100 - y * k)}"


def path_of(name):
    pen = RecordingPen()
    glyphs[name].draw(pen)
    out = []
    cur = None
    for op, args in pen.value:
        if op == "moveTo":
            cur = args[0]
            out.append("M" + pt(cur))
        elif op == "lineTo":
            cur = args[0]
            out.append("L" + pt(cur))
        elif op == "qCurveTo":
            if args[-1] is None:  # closed contour made only of off-curve points: not used by Chivo caps
                raise SystemExit(f"unsupported all-off-curve contour in {name}")
            for c, e in decomposeQuadraticSegment(args):
                out.append("Q" + pt(c) + " " + pt(e))
                cur = e
        elif op == "curveTo":
            raise SystemExit(f"cubic curve in {name}: Chivo TTF should be quadratic")
        elif op in ("closePath", "endPath"):
            out.append("Z")
    return "".join(out)


lines = [
    "// Generated by scripts/bake-brand-type.py from Chivo Black Italic (SIL OFL, see fonts/OFL.txt). Do not edit.",
    "// Each glyph: advance width and outline on a 100-unit cap height (caps from y = 0 to the baseline at y = 100).",
    "export const CHIVO_BLACK_ITALIC: Record<string, { w: number; d: string }> = {",
]
for ch in CHARS:
    name = cmap[ord(ch)]
    adv = font["hmtx"][name][0] * k
    lines.append(f"  {repr(ch) if ch != chr(39) else chr(34) + chr(39) + chr(34)}: {{ w: {fmt(adv)}, d: \"{path_of(name)}\" }},")
space = font["hmtx"][cmap[32]][0] * k
lines.append("};")
lines.append(f"export const CHIVO_SPACE = {fmt(space)};")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
